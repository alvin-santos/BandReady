<?php

namespace Database\Seeders;

use App\Models\Question;
use App\Models\Test;
use Illuminate\Database\Seeder;

/**
 * Ensures every IELTS General Training Speaking test has the AI mock-interview question
 * (`options_json.ielts_speaking.mode` = ai_conversation).
 *
 * Run: php artisan db:seed --class=IeltsAiSpeakingSeeder
 *
 * Replaces all questions on those tests with a single speaking item (same as QuestionSeeder).
 */
class IeltsAiSpeakingSeeder extends Seeder
{
    public function run(): void
    {
        $tests = Test::query()
            ->whereHas('section', fn ($q) => $q->where('name', 'Speaking'))
            ->whereHas('exam', fn ($q) => $q->where('code', 'ielts_general'))
            ->orderBy('id')
            ->get();

        if ($tests->isEmpty()) {
            if ($this->command) {
                $this->command->warn('No tests found: exam code "ielts_general" + section "Speaking". Run TestSeeder / ExamSeeder first.');
            }

            return;
        }

        foreach ($tests as $test) {
            Question::query()->where('test_id', $test->id)->delete();
            Question::query()->create([
                'test_id' => $test->id,
                'type' => 'speaking_prompt',
                'question_text' => 'Complete a full IELTS-style Speaking interview with an AI examiner (Parts 1–3). Use the microphone for each reply. Part 2 includes one minute to prepare before your long turn.',
                'passage_text' => 'Practice only: not a live examiner. Your turns are transcribed and scored from text (Pro: AI feedback).',
                'audio_script' => null,
                'options_json' => ['ielts_speaking' => ['mode' => 'ai_conversation']],
                'correct_answer' => 'IELTS-style interview: answer naturally; develop Part 3 ideas; use the Part 2 preparation minute. Assessed on English use from candidate transcripts.',
                'explanation' => 'The examiner is generated by AI for each session; follow their instructions as in a real test.',
                'order' => 1,
            ]);
            $test->update(['ielts_speaking_picks' => null]);
        }

        if ($this->command) {
            $this->command->info('IELTS AI Speaking: updated '.$tests->count().' test(s).');
            foreach ($tests as $t) {
                $this->command->line('  - #'.$t->id.' '.$t->title);
            }
        }
    }
}
